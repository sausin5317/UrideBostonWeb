document.addEventListener('DOMContentLoaded', function () {
    // Target URL for QR Code & redirection (MUST include https:// so smartphone cameras trigger direct website link prompt)
    var targetUrl = 'https://www.uride-app.com/';

    var currentLang = 'en';
    var lastSubmission = null;

    var qrCanvas = document.getElementById('qrCanvas');
    var qrUrlLabel = document.getElementById('qrUrlLabel');
    var downloadQrBtn = document.getElementById('downloadQrBtn');
    var copyLinkBtn = document.getElementById('copyLinkBtn');
    var copyLinkBtnText = document.getElementById('copyLinkBtnText');
    var submitBtn = document.getElementById('submitBtn');
    var submitBtnText = document.getElementById('submitBtnText');
    var shareWhatsApp = document.getElementById('shareWhatsApp');
    var shareFacebook = document.getElementById('shareFacebook');
    var shareTwitter = document.getElementById('shareTwitter');
    var shareInstagram = document.getElementById('shareInstagram');
    var driverForm = document.getElementById('driverForm');
    var successBox = document.getElementById('successBox');
    var successMessage = document.getElementById('successMessage');
    var registerAnotherBtn = document.getElementById('registerAnotherBtn');

    function t(key) {
        var dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
        return dict[key] !== undefined ? dict[key] : (TRANSLATIONS.en[key] || '');
    }

    function updateSocialLinks() {
        var shareMsg = t('share.msg') + targetUrl;
        var encodedShareMsg = encodeURIComponent(shareMsg);
        var encodedUrl = encodeURIComponent(targetUrl);

        if (shareWhatsApp) {
            shareWhatsApp.href = "https://api.whatsapp.com/send?text=" + encodedShareMsg;
        }
        if (shareFacebook) {
            shareFacebook.href = "https://www.facebook.com/sharer/sharer.php?u=" + encodedUrl;
        }
        if (shareTwitter) {
            shareTwitter.href = "https://twitter.com/intent/tweet?url=" + encodedUrl + "&text=" + encodeURIComponent(t('share.tweet'));
        }
    }

    function setLanguage(lang) {
        if (!TRANSLATIONS[lang]) {
            lang = 'en';
        }
        currentLang = lang;

        try {
            localStorage.setItem('uride_lang', lang);
        } catch (e) {}

        document.documentElement.lang = lang;
        document.title = t('pageTitle');

        var metaDesc = document.querySelector('meta[name="description"]');
        if (metaDesc) {
            metaDesc.setAttribute('content', t('metaDesc'));
        }

        // Update all static text nodes with data-i18n
        var i18nNodes = document.querySelectorAll('[data-i18n]');
        for (var i = 0; i < i18nNodes.length; i++) {
            var node = i18nNodes[i];
            var key = node.getAttribute('data-i18n');
            if (key) {
                node.textContent = t(key);
            }
        }

        // Update all input/textarea placeholders with data-i18n-placeholder
        var placeholderNodes = document.querySelectorAll('[data-i18n-placeholder]');
        for (var j = 0; j < placeholderNodes.length; j++) {
            var pNode = placeholderNodes[j];
            var pKey = pNode.getAttribute('data-i18n-placeholder');
            if (pKey) {
                pNode.setAttribute('placeholder', t(pKey));
            }
        }

        // Update language switcher button states
        var langBtns = document.querySelectorAll('.lang-btn');
        for (var k = 0; k < langBtns.length; k++) {
            var btn = langBtns[k];
            var isMatch = btn.getAttribute('data-lang') === lang;
            if (isMatch) {
                btn.classList.add('active');
                btn.setAttribute('aria-pressed', 'true');
            } else {
                btn.classList.remove('active');
                btn.setAttribute('aria-pressed', 'false');
            }
        }

        // Re-translate any active validation errors currently displayed
        var errorMap = [
            { id: 'nameError', key: 'err.name' },
            { id: 'phoneError', key: 'err.phone' },
            { id: 'emailError', key: 'err.email' },
            { id: 'areaError', key: 'err.area' },
            { id: 'vehicleError', key: 'err.vehicle' },
            { id: 'yearError', key: 'err.year' }
        ];
        for (var m = 0; m < errorMap.length; m++) {
            var errEl = document.getElementById(errorMap[m].id);
            if (errEl && errEl.textContent.trim() !== '') {
                errEl.textContent = t(errorMap[m].key);
            }
        }

        // Re-translate personalized confirmation message if shown
        if (lastSubmission && successBox && successBox.style.display !== 'none' && successMessage) {
            successMessage.textContent = t('form.successPersonalMsg')
                .replace('{name}', lastSubmission.name)
                .replace('{email}', lastSubmission.email)
                .replace('{phone}', lastSubmission.phone);
        }

        updateSocialLinks();
    }

    // Bind Language Switcher Buttons
    var langButtons = document.querySelectorAll('.lang-btn');
    for (var b = 0; b < langButtons.length; b++) {
        langButtons[b].addEventListener('click', function () {
            var selectedLang = this.getAttribute('data-lang');
            setLanguage(selectedLang);
        });
    }

    // Determine initial language: URL ?lang= param -> localStorage -> default 'en'
    var initialLang = 'en';
    try {
        var urlParams = new URLSearchParams(window.location.search);
        var queryLang = (urlParams.get('lang') || '').toLowerCase();
        var savedLang = (localStorage.getItem('uride_lang') || '').toLowerCase();
        if (TRANSLATIONS[queryLang]) {
            initialLang = queryLang;
        } else if (TRANSLATIONS[savedLang]) {
            initialLang = savedLang;
        }
    } catch (e) {}

    setLanguage(initialLang);

    if (qrUrlLabel) {
        qrUrlLabel.textContent = targetUrl;
    }

    // Render Scannable QR Code
    if (qrCanvas && window.QRCodeGenerator) {
        window.QRCodeGenerator.renderToCanvas(qrCanvas, targetUrl, {
            size: 240,
            foreground: '#000000', // Pure high-contrast black for instant phone camera detection
            background: '#FFFFFF',
            correctLevel: 1 // Level M
        });
    }

    // Download QR Code as PNG
    if (downloadQrBtn && qrCanvas) {
        downloadQrBtn.addEventListener('click', function () {
            var link = document.createElement('a');
            link.download = 'uride-app-qr.png';
            link.href = qrCanvas.toDataURL('image/png');
            link.click();
        });
    }

    // Copy Link
    if (copyLinkBtn) {
        copyLinkBtn.addEventListener('click', function () {
            var showCopiedFeedback = function () {
                if (copyLinkBtnText) {
                    copyLinkBtnText.textContent = t('qr.copiedBtn');
                    setTimeout(function () {
                        copyLinkBtnText.textContent = t('qr.copyBtn');
                    }, 2000);
                }
            };

            if (navigator.clipboard && navigator.clipboard.writeText) {
                navigator.clipboard.writeText(targetUrl).then(showCopiedFeedback);
            } else {
                var temp = document.createElement('input');
                temp.value = targetUrl;
                document.body.appendChild(temp);
                temp.select();
                document.execCommand('copy');
                document.body.removeChild(temp);
                showCopiedFeedback();
            }
        });
    }

    // Instagram / Native Share
    if (shareInstagram) {
        shareInstagram.addEventListener('click', function () {
            var shareMsg = t('share.msg') + targetUrl;
            if (navigator.share) {
                navigator.share({
                    title: t('share.title'),
                    text: shareMsg,
                    url: targetUrl
                }).catch(function () {});
            } else if (navigator.clipboard && navigator.clipboard.writeText) {
                navigator.clipboard.writeText(shareMsg).then(function () {
                    var span = shareInstagram.querySelector('span');
                    if (span) span.textContent = t('qr.copiedBtn');
                    setTimeout(function () { if (span) span.textContent = 'Instagram'; }, 2200);
                });
            }
        });
    }

    if (driverForm) {
        driverForm.addEventListener('submit', function (e) {
            e.preventDefault();

            var fullName = document.getElementById('fullName').value.trim();
            var phone = document.getElementById('phone').value.trim();
            var email = document.getElementById('email').value.trim();
            var area = document.getElementById('area').value.trim();
            var vehicle = document.getElementById('vehicle').value.trim();
            var vehicleYear = document.getElementById('vehicleYear').value.trim();

            // Clear errors
            document.getElementById('nameError').textContent = '';
            document.getElementById('phoneError').textContent = '';
            document.getElementById('emailError').textContent = '';
            document.getElementById('areaError').textContent = '';
            document.getElementById('vehicleError').textContent = '';
            document.getElementById('yearError').textContent = '';

            var hasError = false;

            if (!fullName) {
                document.getElementById('nameError').textContent = t('err.name');
                hasError = true;
            }
            if (!phone) {
                document.getElementById('phoneError').textContent = t('err.phone');
                hasError = true;
            }
            if (!email || !email.includes('@')) {
                document.getElementById('emailError').textContent = t('err.email');
                hasError = true;
            }
            if (!area) {
                document.getElementById('areaError').textContent = t('err.area');
                hasError = true;
            }
            if (!vehicle) {
                document.getElementById('vehicleError').textContent = t('err.vehicle');
                hasError = true;
            }
            if (!vehicleYear) {
                document.getElementById('yearError').textContent = t('err.year');
                hasError = true;
            }

            if (hasError) return;

            if (submitBtn) {
                submitBtn.disabled = true;
                if (submitBtnText) {
                    submitBtnText.textContent = t('form.submittingBtn');
                }
            }

            var langLabel = (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang].langName) || 'English';

            var record = {
                "Full Name": fullName,
                "Phone Number": phone,
                "Email Address": email,
                "Boston Area": area,
                "Vehicle": vehicleYear + ' ' + vehicle,
                "Driving Background": document.getElementById('experience').value,
                "Preferred Language": langLabel,
                "Notes / Availability": document.getElementById('comments').value.trim() || 'None',
                "Submitted At": new Date().toLocaleString()
            };

            // 1. Local backup in browser
            var submissions = [];
            try {
                submissions = JSON.parse(localStorage.getItem('uride_driver_registrations') || '[]');
            } catch (err) {
                submissions = [];
            }
            submissions.push(record);
            localStorage.setItem('uride_driver_registrations', JSON.stringify(submissions));

            // 2. Direct email delivery to brandaovicente4@gmail.com
            var payload = {
                name: fullName,
                phone: phone,
                email: email,
                area: area,
                vehicle: vehicleYear + ' ' + vehicle,
                background: document.getElementById('experience').value,
                preferred_language: langLabel,
                notes: document.getElementById('comments').value.trim() || 'N/A',
                _subject: "New Uride Boston Driver Registration (" + langLabel + "): " + fullName,
                _template: "table",
                _captcha: "false"
            };

            // Optional Google Apps Script Webhook URL (if configured)
            var googleSheetWebhookUrl = localStorage.getItem('uride_google_sheet_webhook') || '';

            // Send to brandaovicente4@gmail.com
            fetch('https://formsubmit.co/ajax/brandaovicente4@gmail.com', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'Accept': 'application/json'
                },
                body: JSON.stringify(payload)
            }).catch(function (err) {
                console.log('Form submission network notification:', err);
            });

            // If Google Sheet Webhook is configured, also post to Google Sheet
            if (googleSheetWebhookUrl) {
                fetch(googleSheetWebhookUrl, {
                    method: 'POST',
                    mode: 'no-cors',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify(record)
                }).catch(function (e) { console.log('Google sheet post:', e); });
            }

            lastSubmission = {
                name: fullName,
                email: email,
                phone: phone
            };

            // Show success message
            driverForm.style.display = 'none';
            if (submitBtn) {
                submitBtn.disabled = false;
                if (submitBtnText) {
                    submitBtnText.textContent = t('form.submitBtn');
                }
            }
            if (successBox) {
                successBox.style.display = 'block';
                if (successMessage) {
                    successMessage.textContent = t('form.successPersonalMsg')
                        .replace('{name}', fullName)
                        .replace('{email}', email)
                        .replace('{phone}', phone);
                }
            }
        });
    }

    if (registerAnotherBtn) {
        registerAnotherBtn.addEventListener('click', function () {
            lastSubmission = null;
            if (driverForm) {
                driverForm.reset();
                driverForm.style.display = 'block';
            }
            if (successBox) {
                successBox.style.display = 'none';
            }
        });
    }
});
